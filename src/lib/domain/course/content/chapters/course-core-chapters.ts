import type { CourseChapterDefinition, CourseWord } from '../../path-types.ts';

import type { Article, CefrLevel, LexemeKind, VerbForms } from '../../../types.ts';

function noun(
  german: string,
  czech: string,
  article: Article,
  plural: string,
  cefr: CefrLevel,
  exampleDe: string,
  exampleCs: string,
): CourseWord {
  return { german, czech, kind: 'noun', article, plural, cefr, exampleDe, exampleCs };
}

function verb(
  german: string,
  czech: string,
  cefr: CefrLevel,
  exampleDe: string,
  exampleCs: string,
  verbForms?: VerbForms,
): CourseWord {
  return { german, czech, kind: 'verb', cefr, exampleDe, exampleCs, verbForms };
}

function other(
  german: string,
  czech: string,
  kind: Exclude<LexemeKind, 'noun' | 'verb'>,
  cefr: CefrLevel,
  exampleDe: string,
  exampleCs: string,
): CourseWord {
  return { german, czech, kind, cefr, exampleDe, exampleCs };
}

