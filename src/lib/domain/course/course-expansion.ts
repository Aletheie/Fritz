import type { StoryBookId } from '../stories/types.ts';
import type { Article, CefrLevel, LexemeKind, VerbForms } from '../types.ts';
import type { CourseChapterDefinition, CourseModelSentence, CourseWord } from './path.ts';

type DetailedLevel = CourseChapterDefinition['level'];

type ChapterSpec = {
  id: string;
  level: DetailedLevel;
  title: string;
  situation: string;
  mission: string;
  outcomes: [string, string, string];
  grammarLessonIds: [string, ...string[]];
  coachScenarioIds: [string, ...string[]];
  storyBookId: StoryBookId;
  grammarIdea: string;
  grammarPattern: string;
  words: CourseWord[];
  reviewWords: string[];
  sentences: CourseModelSentence[];
  sentencePrompt: string;
  sentenceStarter: string;
  dialogue: CourseChapterDefinition['dialogue'];
};

function noun(
  german: string,
  czech: string,
  article: Article,
  plural: string,
  cefr: CefrLevel,
  exampleDe: string,
  exampleCs: string,
  collocation: string,
  acceptedCzech: string[] = [],
): CourseWord {
  return {
    german,
    czech,
    kind: 'noun',
    article,
    plural,
    cefr,
    exampleDe,
    exampleCs,
    collocations: [collocation],
    contexts: [exampleDe],
    acceptedCzech,
  };
}

function verb(
  german: string,
  czech: string,
  cefr: CefrLevel,
  forms: [string, string, string, VerbForms['auxiliary']],
  exampleDe: string,
  exampleCs: string,
  collocation: string,
  acceptedCzech: string[] = [],
): CourseWord {
  return {
    german,
    czech,
    kind: 'verb',
    cefr,
    verbForms: {
      thirdPerson: forms[0],
      preterite: forms[1],
      participle: forms[2],
      auxiliary: forms[3],
    },
    exampleDe,
    exampleCs,
    collocations: [collocation],
    contexts: [exampleDe],
    acceptedCzech,
  };
}

function term(
  german: string,
  czech: string,
  kind: Exclude<LexemeKind, 'noun' | 'verb'>,
  cefr: CefrLevel,
  exampleDe: string,
  exampleCs: string,
  collocation: string,
  acceptedCzech: string[] = [],
): CourseWord {
  return {
    german,
    czech,
    kind,
    cefr,
    exampleDe,
    exampleCs,
    collocations: [collocation],
    contexts: [exampleDe],
    acceptedCzech,
  };
}

function model(de: string, cs: string, trap: string, note: string): CourseModelSentence {
  return { de, cs, trap, note };
}

function slug(value: string): string {
  return value
    .normalize('NFKD')
    .replace(/\p{M}+/gu, '')
    .toLocaleLowerCase('de-DE')
    .replace(/[^a-z0-9]+/gu, '-')
    .replace(/^-|-$/gu, '');
}

function lexemeId(lemma: string): string {
  const normalized = slug(lemma);
  const correctedSense: Record<string, string> = {
    Gleis: 'railway-track-platform-context',
    Frist: 'deadline-period',
    Voraussetzung: 'necessary-precondition',
  };
  return `lexeme:${normalized}:${slug(correctedSense[lemma] ?? `${normalized}:default`)}`;
}

function chapter(spec: ChapterSpec): CourseChapterDefinition {
  return {
    id: spec.id,
    number: 0,
    level: spec.level,
    title: spec.title,
    subtitle: spec.situation,
    situation: spec.situation,
    themeTag: spec.id.replace(/^chapter-\d+-/u, ''),
    grammarLessonId: spec.grammarLessonIds[0],
    grammarLessonIds: spec.grammarLessonIds,
    coachScenarioId: spec.coachScenarioIds[0],
    coachScenarioIds: spec.coachScenarioIds,
    storyBookId: spec.storyBookId,
    readingIds: [spec.storyBookId],
    grammarIdea: spec.grammarIdea,
    mission: spec.mission,
    outcomes: spec.outcomes,
    grammarPattern: spec.grammarPattern,
    modelSentences: spec.sentences,
    sentencePrompt: spec.sentencePrompt,
    sentenceStarter: spec.sentenceStarter,
    sentenceChecklist: [
      'výstup odpovídá zadané situaci',
      'obsahuje alespoň jeden cílový výraz',
      'splňuje hlavní gramatické pravidlo kapitoly',
    ],
    words: spec.words,
    reviewLexemeIds: spec.reviewWords.map(lexemeId),
    dialogue: spec.dialogue,
    assessment: {
      id: `${spec.id}:assessment`,
      instruction: spec.sentencePrompt,
      criteria: [spec.outcomes[0], spec.outcomes[1], 'sdělení je významově úplné a srozumitelné'],
      deterministic: true,
    },
    contentVersion: 2,
  };
}

