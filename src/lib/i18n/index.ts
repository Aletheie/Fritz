function interpolate(template: string, variables?: Variables): string {
  if (!variables) return template;
  return template.replace(/\{([a-zA-Z][\w]*)\}/gu, (match, key: string) => {
    const value = variables[key];
    return value === undefined ? match : String(value);
  });
}

export function t(language: MotherTongue, key: TranslationKey, variables?: Variables): string {
  return interpolate(language === 'en' ? english[key] : czech[key], variables);
}

export function localized(language: MotherTongue, value: { cs: string; en: string }): string {
  return language === 'en' ? value.en : value.cs;
}

export function languageTag(language: MotherTongue): 'cs-CZ' | 'en-US' {
  return language === 'en' ? 'en-US' : 'cs-CZ';
}

export function formatNumber(language: MotherTongue, value: number): string {
  return numberFormatters[language].format(value);
}

