export function coachScenarioCopy(scenario: CoachScenario, language: MotherTongue): CoachScenario {
  if (language === 'cs') return scenario;
  const title = englishTitles[scenario.id] ?? 'German conversation practice';
  return {
    ...scenario,
    title,
    eyebrow: `Role-play · ${scenario.level} speaking`,
    description: `Use German to handle “${title}” in a short, focused conversation.`,
    goal: 'Complete three clear, natural turns in German.',
    openingCs: 'Your conversation partner opens the situation in German.',
    learnerRole: 'learner',
    coachRole: 'conversation partner',
    guidedHints: scenario.guidedHints?.map((hint, index) => ({
      ...hint,
      label: `Useful phrase ${index + 1}`,
      czech: 'Tap the German model answer to place it in your reply.',
    })),
  };
}

export function coachScenarioTitle(id: string, fallback: string, language: MotherTongue): string {
  return language === 'en' ? (englishTitles[id] ?? fallback) : fallback;
}
