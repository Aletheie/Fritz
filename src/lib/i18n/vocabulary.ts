const normalizedEnglishByGerman = new Map(
  Object.entries({
    ...englishByGerman,
    ...courseTopicEnglishByGerman,
    ...storyEnglishByGerman,
  }).map(([german, english]) => [german.trim().toLocaleLowerCase('de-DE'), english]),
);

function englishMeaning(german: string, fallback: string): string {
  return normalizedEnglishByGerman.get(german.trim().toLocaleLowerCase('de-DE')) ?? fallback;
}

export function sourceMeaning(german: string, fallback: string, language: MotherTongue): string {
  return language === 'en' ? englishMeaning(german, fallback) : fallback;
}

export function hasEnglishCourseMeaning(german: string): boolean {
  return normalizedEnglishByGerman.has(german.trim().toLocaleLowerCase('de-DE'));
}

export function noteMeaning(note: Pick<Note, 'german' | 'czech'>, language: MotherTongue): string {
  return language === 'en' ? englishMeaning(note.german, note.czech) : note.czech;
}

const noteSearchIndex = new WeakMap<Note, Partial<Record<MotherTongue, string>>>();

export function noteSearchText(note: Note, language: MotherTongue): string {
  let indexed = noteSearchIndex.get(note);
  if (!indexed) {
    indexed = {};
    noteSearchIndex.set(note, indexed);
  }
  const cached = indexed[language];
  if (cached !== undefined) return cached;
  const value = [
    note.article,
    note.german,
    note.czech,
    noteMeaning(note, language),
    note.plural,
    note.tags.join(' '),
    note.verbForms?.thirdPerson,
    note.verbForms?.preterite,
    note.verbForms?.participle,
  ]
    .filter(Boolean)
    .join(' ')
    .toLocaleLowerCase('cs-CZ');
  indexed[language] = value;
  return value;
}

export function courseWordMeaning(
  word: Pick<CourseWord, 'german' | 'czech'>,
  language: MotherTongue,
): string {
  return language === 'en' ? englishMeaning(word.german, word.czech) : word.czech;
}

export function noteExampleTranslation(
  note: Pick<Note, 'german' | 'exampleCs'>,
  language: MotherTongue,
): string | undefined {
  if (language === 'cs') return note.exampleCs;
  const examples: Record<string, string> = {
    Hund: 'The dog is sleeping under the table.',
    lernen: 'I study German every evening.',
  };
  return examples[note.german];
}
